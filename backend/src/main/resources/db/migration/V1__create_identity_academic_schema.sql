-- ============================================
-- V1: Identity and Academic Administration
-- ============================================

CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    phone VARCHAR(25),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_app_users_email
ON app_users (LOWER(email));


CREATE TABLE app_user_roles (
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('ADMIN', 'TEACHER', 'GUARDIAN', 'STUDENT')),
    PRIMARY KEY (user_id, role)
);


CREATE TABLE teacher_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_users(id),
    employee_code VARCHAR(30) NOT NULL UNIQUE,
    hire_date DATE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);


CREATE TABLE guardian_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_users(id),
    alternate_phone VARCHAR(25)
);


CREATE TABLE school_classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255)
);


CREATE TABLE sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_class_id BIGINT NOT NULL REFERENCES school_classes(id),
    section_name VARCHAR(20) NOT NULL,
    academic_year VARCHAR(9) NOT NULL,
    CONSTRAINT uq_section_year
        UNIQUE (school_class_id, section_name, academic_year)
);


CREATE TABLE subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);


CREATE TABLE students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT UNIQUE REFERENCES app_users(id),
    admission_number VARCHAR(40) NOT NULL UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    date_of_birth DATE,
    admission_date DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'GRADUATED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE student_guardians (
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    guardian_id BIGINT NOT NULL REFERENCES guardian_profiles(id),
    relationship VARCHAR(30) NOT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (student_id, guardian_id)
);

CREATE UNIQUE INDEX uq_student_primary_guardian
ON student_guardians(student_id)
WHERE is_primary = TRUE;


CREATE TABLE student_enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id),
    section_id BIGINT NOT NULL REFERENCES sections(id),
    start_date DATE NOT NULL DEFAULT CURRENT_DATE,
    end_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_enrollment_dates
        CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT uq_student_enrollment
        UNIQUE (student_id, section_id, start_date)
);

CREATE UNIQUE INDEX uq_student_active_enrollment
ON student_enrollments(student_id)
WHERE end_date IS NULL;


CREATE TABLE teacher_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES teacher_profiles(id),
    section_id BIGINT NOT NULL REFERENCES sections(id),
    subject_id BIGINT NOT NULL REFERENCES subjects(id),
    assigned_on DATE NOT NULL DEFAULT CURRENT_DATE,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX uq_teacher_active_assignment
ON teacher_assignments(teacher_id, section_id, subject_id)
WHERE active = TRUE;


-- ============================================
-- Performance indexes
-- ============================================

CREATE INDEX idx_students_admission_number
ON students(admission_number);

CREATE INDEX idx_student_guardians_guardian
ON student_guardians(guardian_id);

CREATE INDEX idx_enrollments_section
ON student_enrollments(section_id);

CREATE INDEX idx_teacher_assignments_section
ON teacher_assignments(section_id);

CREATE INDEX idx_teacher_assignments_teacher
ON teacher_assignments(teacher_id);
