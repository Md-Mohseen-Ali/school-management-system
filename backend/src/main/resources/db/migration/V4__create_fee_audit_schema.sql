-- ============================================
-- V4: Fee Management and Audit Logs
-- ============================================

-- Fee invoices
CREATE TABLE fee_invoices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    invoice_number VARCHAR(40) NOT NULL UNIQUE,

    student_id BIGINT NOT NULL REFERENCES students(id),

    academic_year VARCHAR(9) NOT NULL,

    issue_date DATE NOT NULL DEFAULT CURRENT_DATE,

    due_date DATE NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'ISSUED'
        CHECK (status IN ('DRAFT', 'ISSUED', 'CANCELLED')),

    created_by BIGINT REFERENCES app_users(id),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_invoice_dates
        CHECK (due_date >= issue_date)
);


-- Invoice line items
CREATE TABLE fee_invoice_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    invoice_id BIGINT NOT NULL
        REFERENCES fee_invoices(id) ON DELETE CASCADE,

    description VARCHAR(150) NOT NULL,

    amount NUMERIC(12,2) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_invoice_item_amount
        CHECK (amount > 0)
);


-- Fee payments (simulated payments only)
CREATE TABLE fee_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    invoice_id BIGINT NOT NULL REFERENCES fee_invoices(id),

    payment_reference VARCHAR(60) NOT NULL UNIQUE,

    idempotency_key VARCHAR(100) NOT NULL UNIQUE,

    amount NUMERIC(12,2) NOT NULL,

    payment_method VARCHAR(20) NOT NULL DEFAULT 'SIMULATED'
        CHECK (payment_method IN ('SIMULATED', 'CASH')),

    payment_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (payment_status IN (
            'PENDING', 'SUCCEEDED', 'FAILED', 'REFUNDED'
        )),

    received_by BIGINT REFERENCES app_users(id),

    paid_at TIMESTAMPTZ,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_payment_amount
        CHECK (amount > 0),

    CONSTRAINT chk_successful_payment_date
        CHECK (
            payment_status <> 'SUCCEEDED'
            OR paid_at IS NOT NULL
        )
);


-- Audit trail for material business actions
CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    actor_user_id BIGINT REFERENCES app_users(id) ON DELETE SET NULL,

    action VARCHAR(80) NOT NULL,

    entity_type VARCHAR(80) NOT NULL,

    entity_id VARCHAR(80) NOT NULL,

    old_values JSONB,

    new_values JSONB,

    request_id VARCHAR(100),

    ip_address VARCHAR(45),

    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);


-- ============================================
-- Performance indexes
-- ============================================

CREATE INDEX idx_fee_invoices_student
ON fee_invoices(student_id);

CREATE INDEX idx_fee_invoices_status
ON fee_invoices(status);

CREATE INDEX idx_fee_invoices_due_date
ON fee_invoices(due_date);

CREATE INDEX idx_fee_invoice_items_invoice
ON fee_invoice_items(invoice_id);

CREATE INDEX idx_fee_payments_invoice
ON fee_payments(invoice_id);

CREATE INDEX idx_fee_payments_status
ON fee_payments(payment_status);

CREATE INDEX idx_audit_logs_actor
ON audit_logs(actor_user_id);

CREATE INDEX idx_audit_logs_entity
ON audit_logs(entity_type, entity_id);

CREATE INDEX idx_audit_logs_occurred
ON audit_logs(occurred_at);
