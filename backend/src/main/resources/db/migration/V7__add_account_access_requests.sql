-- Public access requests are stored separately from authenticated identities.
-- A login is created only after an administrator verifies and approves the request.
CREATE TABLE account_access_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requested_role VARCHAR(20) NOT NULL
        CHECK (requested_role IN ('TEACHER', 'GUARDIAN', 'STUDENT')),
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(180) NOT NULL,
    phone VARCHAR(25),
    employee_code VARCHAR(30),
    hire_date DATE,
    alternate_phone VARCHAR(25),
    admission_number VARCHAR(40),
    first_name VARCHAR(80),
    last_name VARCHAR(80),
    date_of_birth DATE,
    student_admission_number VARCHAR(40),
    relationship VARCHAR(30),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    review_note VARCHAR(500),
    reviewed_by_user_id BIGINT REFERENCES app_users(id),
    reviewed_at TIMESTAMPTZ,
    provisioned_entity_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX idx_account_access_requests_status_created
    ON account_access_requests(status, created_at DESC);

CREATE UNIQUE INDEX uq_account_access_requests_pending_email_role
    ON account_access_requests(LOWER(email), requested_role)
    WHERE status = 'PENDING';

COMMENT ON TABLE account_access_requests IS
    'Untrusted access requests; no app_user is created until an administrator approves.';
