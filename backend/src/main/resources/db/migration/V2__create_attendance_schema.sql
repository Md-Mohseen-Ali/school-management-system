-- ============================================
-- V2: Attendance Management
-- ============================================

-- One attendance session per section, date and session code.
CREATE TABLE attendance_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    section_id BIGINT NOT NULL
        REFERENCES sections(id),

    marked_by_teacher_id BIGINT NOT NULL
        REFERENCES teacher_profiles(id),

    attendance_date DATE NOT NULL,

    session_code VARCHAR(20) NOT NULL DEFAULT 'FULL_DAY',

    status VARCHAR(15) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'SUBMITTED', 'LOCKED')),

    notes VARCHAR(255),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    submitted_at TIMESTAMPTZ,

    CONSTRAINT uq_attendance_section_date_session
        UNIQUE (section_id, attendance_date, session_code),

    CONSTRAINT chk_attendance_session_code
        CHECK (BTRIM(session_code) <> '')
);


-- Attendance records for individual students.
CREATE TABLE attendance_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    attendance_session_id BIGINT NOT NULL
        REFERENCES attendance_sessions(id) ON DELETE CASCADE,

    student_id BIGINT NOT NULL
        REFERENCES students(id),

    attendance_status VARCHAR(15) NOT NULL
        CHECK (
            attendance_status IN (
                'PRESENT',
                'ABSENT',
                'LATE',
                'EXCUSED'
            )
        ),

    remarks VARCHAR(255),

    marked_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Prevent duplicate attendance for one student in one session.
    CONSTRAINT uq_attendance_student_session
        UNIQUE (attendance_session_id, student_id)
);


-- ============================================
-- Performance indexes
-- ============================================

CREATE INDEX idx_attendance_sessions_section_date
ON attendance_sessions(section_id, attendance_date);

CREATE INDEX idx_attendance_sessions_teacher
ON attendance_sessions(marked_by_teacher_id);

CREATE INDEX idx_attendance_records_student
ON attendance_records(student_id);

CREATE INDEX idx_attendance_records_status
ON attendance_records(attendance_status);
