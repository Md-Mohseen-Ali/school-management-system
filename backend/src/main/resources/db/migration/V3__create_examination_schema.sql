-- ============================================
-- V3: Examinations and Results
-- ============================================

-- Examination master
CREATE TABLE examinations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    section_id BIGINT NOT NULL REFERENCES sections(id),

    exam_name VARCHAR(100) NOT NULL,

    academic_year VARCHAR(9) NOT NULL,

    start_date DATE NOT NULL,

    end_date DATE NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN (
            'DRAFT',
            'SCHEDULED',
            'COMPLETED',
            'PUBLISHED'
        )),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_exam_dates
        CHECK (end_date >= start_date),

    CONSTRAINT uq_examination_section
        UNIQUE (section_id, exam_name, academic_year)
);


-- Subject-wise examination configuration
CREATE TABLE examination_subjects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    examination_id BIGINT NOT NULL
        REFERENCES examinations(id) ON DELETE CASCADE,

    subject_id BIGINT NOT NULL REFERENCES subjects(id),

    examination_date DATE NOT NULL,

    max_marks NUMERIC(7,2) NOT NULL,

    pass_marks NUMERIC(7,2) NOT NULL,

    CONSTRAINT chk_max_marks
        CHECK (max_marks > 0),

    CONSTRAINT chk_pass_marks
        CHECK (pass_marks >= 0 AND pass_marks <= max_marks),

    CONSTRAINT uq_examination_subject
        UNIQUE (examination_id, subject_id)
);


-- Configurable grading rules
CREATE TABLE grading_scales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    academic_year VARCHAR(9) NOT NULL,

    grade VARCHAR(5) NOT NULL,

    min_percentage NUMERIC(5,2) NOT NULL,

    max_percentage NUMERIC(5,2) NOT NULL,

    remarks VARCHAR(100),

    CONSTRAINT chk_grade_percentage
        CHECK (
            min_percentage >= 0
            AND max_percentage <= 100
            AND min_percentage <= max_percentage
        ),

    CONSTRAINT uq_grade_academic_year
        UNIQUE (academic_year, grade)
);


-- Student-wise subject marks
CREATE TABLE examination_marks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    examination_subject_id BIGINT NOT NULL
        REFERENCES examination_subjects(id) ON DELETE CASCADE,

    student_id BIGINT NOT NULL
        REFERENCES students(id),

    marks_obtained NUMERIC(7,2) NOT NULL,

    attendance_status VARCHAR(15) NOT NULL DEFAULT 'PRESENT'
        CHECK (attendance_status IN ('PRESENT', 'ABSENT')),

    remarks VARCHAR(255),

    entered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_marks_non_negative
        CHECK (marks_obtained >= 0),

    CONSTRAINT chk_absent_marks
        CHECK (
            attendance_status <> 'ABSENT'
            OR marks_obtained = 0
        ),

    CONSTRAINT uq_student_exam_subject
        UNIQUE (examination_subject_id, student_id)
);


-- ============================================
-- Performance indexes
-- ============================================

CREATE INDEX idx_examinations_section
ON examinations(section_id);

CREATE INDEX idx_examinations_academic_year
ON examinations(academic_year);

CREATE INDEX idx_examination_subjects_exam
ON examination_subjects(examination_id);

CREATE INDEX idx_examination_marks_student
ON examination_marks(student_id);

CREATE INDEX idx_grading_scales_year
ON grading_scales(academic_year);
